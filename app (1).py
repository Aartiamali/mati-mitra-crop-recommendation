@app.route('/predict', methods=['GET', 'POST'])
def predict():
    if request.method == 'POST':
        city = request.form.get('city', '').strip()

        # ---- Step 1: check all required fields are numbers ----
        try:
            N = float(request.form['N'])
            P = float(request.form['P'])
            K = float(request.form['K'])
            ph = float(request.form['ph'])
            rainfall = float(request.form['rainfall'])
        except (ValueError, KeyError):
            return render_template('predict.html', error="कृपया सगळ्या रकान्यांत योग्य आकडे भरा (शब्द किंवा रिकामी जागा चालणार नाही).", district_values=district_typical_values)

        language = request.form.get('language', 'mr')

        # ---- Step 2: sensible range checks ----
        if not city:
            return render_template('predict.html', error="कृपया शहर / जिल्ह्याचं नाव टाका.", district_values=district_typical_values)
        if not (0 <= N <= 150):
            return render_template('predict.html', error="नत्र (N) ची किंमत 0 ते 150 च्या दरम्यान असावी.", district_values=district_typical_values)
        if not (0 <= P <= 150):
            return render_template('predict.html', error="स्फुरद (P) ची किंमत 0 ते 150 च्या दरम्यान असावी.", district_values=district_typical_values)
        if not (0 <= K <= 210):
            return render_template('predict.html', error="पालाश (K) ची किंमत 0 ते 210 च्या दरम्यान असावी.", district_values=district_typical_values)
        if not (0 <= ph <= 14):
            return render_template('predict.html', error="जमिनीचा pH 0 ते 14 च्या दरम्यानच असू शकतो.", district_values=district_typical_values)
        if not (0 <= rainfall <= 500):
            return render_template('predict.html', error="पर्जन्यमान 0 ते 500 मिमी च्या दरम्यान असावं.", district_values=district_typical_values)

        temp, humidity = get_weather(city)
        weather_error = None
        if temp is None:
            weather_error = "⚠️ हवामान माहिती मिळाली नाही (इंटरनेट कनेक्शन तपासा किंवा शहराचं नाव बरोबर टाका). अंदाजे सरासरी मूल्य वापरून निकाल दाखवत आहोत."
            temp, humidity = 25, 70

        forecast = get_forecast(city)
        if language != 'mr':
            for day in forecast:
                day['desc'] = translate_text_field(day['desc'], language)

        sample = [N, P, K, temp, humidity, ph, rainfall]

        irrigation = request.form.get('irrigation', 'no') == 'yes'
        waterlogging = request.form.get('waterlogging', 'no') == 'yes'

        top3, other_crops = predict_top3_split(sample, city, ph, rainfall, irrigation, waterlogging)

        # ---- Input plausibility check (Option B) ----
        plausibility_warning = None
        city_key_check = city.lower().strip()
        if city_key_check in district_typical_values:
            typical = district_typical_values[city_key_check]
            issues = []
            if abs(ph - typical['ph']) > 1.5:
                issues.append(f"pH ({ph}, साधारण {typical['ph']} अपेक्षित)")
            if abs(N - typical['N']) > 30:
                issues.append(f"नत्र N ({N}, साधारण {typical['N']} अपेक्षित)")
            if abs(P - typical['P']) > 25:
                issues.append(f"स्फुरद P ({P}, साधारण {typical['P']} अपेक्षित)")
            if abs(K - typical['K']) > 25:
                issues.append(f"पालाश K ({K}, साधारण {typical['K']} अपेक्षित)")
            if issues:
                plausibility_warning = f"⚠️ {city} भागासाठी हे मूल्य असामान्य वाटतात — " + ", ".join(issues) + ". कृपया एकदा तपासून बघा."

        best_crop = top3[0][0]
        confidence = top3[0][1]

        fert_raw = fertilizer_recommendation(N, P, K, best_crop.lower())
        info = crop_info.get(best_crop.lower(), {'water': 'N/A', 'season': 'N/A'})
        last_crop = request.form.get('last_crop', '').strip()
        rotation = crop_rotation_suggestion(best_crop, language, last_crop if last_crop else None)

        conf_label = confidence_label(confidence, language)
        sowing_timing = check_sowing_timing(info['season'], language)
        emoji = crop_emoji.get(best_crop.lower(), '🌱')

        # Translate the fixed-value fields (water need, season, fertilizer status)
        water_localized = translate_fixed(info['water'], WATER_MAP, language, info['water'])
        season_localized = translate_fixed(info['season'], SEASON_MAP, language, info['season'])
        fert = tuple(translate_fixed(f, FERT_MAP, language, f) for f in fert_raw)

        # Translate crop names themselves too, so the whole result feels native
        # (uses our own verified dictionary for mr/hi, avoiding mistranslation bugs)
        translated_top3 = [
            (translate_crop_name(crop, language), conf)
            for crop, conf in top3
        ]
        translated_other = [
            (translate_crop_name(crop, language), conf)
            for crop, conf in other_crops
        ]

        # Relative share among the shown top-3 (sums to 100), for the donut chart —
        # a DIFFERENT number from the raw model confidence, used only to compare
        # the 2-3 options against each other, not as an absolute accuracy score.
        raw_sum = sum(c for _, c in top3) or 1
        top3_relative = []
        for name, c in translated_top3:
            rel = c / raw_sum * 100
            rel_display = round(rel, 1) if rel >= 1 else round(rel, 2)
            top3_relative.append((name, rel_display))

        donut_colors = ['#4A7C59', '#D4972B', '#A8442B']
        cursor = 0.0
        gradient_stops = []
        for i, (name, pct) in enumerate(top3_relative):
            color = donut_colors[i % len(donut_colors)]
            start = cursor
            end = cursor + pct
            gradient_stops.append(f"{color} {start:.1f}% {end:.1f}%")
            cursor = end
        donut_gradient = "conic-gradient(" + ", ".join(gradient_stops) + ")"
        top3_with_colors = [
            (name, conf, top3_relative[i][1], donut_colors[i % len(donut_colors)])
            for i, (name, conf) in enumerate(translated_top3)
        ]

        # ---- Build the FULL result as one narration, in the selected language ----
        crop_label = translate_fixed('crop', LABEL_MAP, language, LABEL_MAP['en']['crop'])
        water_label = translate_fixed('water', LABEL_MAP, language, LABEL_MAP['en']['water'])
        season_label = translate_fixed('season', LABEL_MAP, language, LABEL_MAP['en']['season'])
        fert_label = translate_fixed('fert', LABEL_MAP, language, LABEL_MAP['en']['fert'])
        rotation_label = translate_fixed('rotation', LABEL_MAP, language, LABEL_MAP['en']['rotation'])

        best_crop_name_localized = translated_top3[0][0]

        translated_text = (
            f"{crop_label}: {best_crop_name_localized}. {conf_label}. "
            f"{water_label}: {water_localized}. "
            f"{season_label}: {season_localized}. "
            f"{sowing_timing}. "
            f"{fert_label}: {fert[0]}, {fert[1]}, {fert[2]}. "
            f"{rotation_label}: {rotation}"
        )
        tts = gTTS(text=translated_text, lang=language)
        tts.save("static/audio_output.mp3")

        result = {
            'top3': translated_top3,
            'other': translated_other,
            'fertilizer': fert,
            'water': water_localized,
            'season': season_localized,
            'rotation': rotation,
            'temp': temp,
            'humidity': humidity,
            'translated_text': translated_text,
            'confidence_label': conf_label,
            'sowing_timing': sowing_timing,
            'weather_error': weather_error,
            'crop_emoji': emoji,
            'crop_key': best_crop.lower(),
            'donut_gradient': donut_gradient,
            'top3_with_colors': top3_with_colors,
            'plausibility_warning': plausibility_warning,
            'forecast': forecast
        }

        return render_template('result.html', result=result, language=language, ui=get_result_page_ui(language))

    return render_template('predict.html', district_values=district_typical_values)


