def translate_text_field(text, lang, _retries=2):
    """Translate one piece of body text into the target language. Marathi
    is the native language of the crop-detail content, so lang='mr'
    returns the text unchanged (no API call, fast default). Retries a
    couple of times on failure — the free translation backend can be
    flaky under many rapid sequential calls (a single crop page makes
    20-30+ of these), and one retry usually succeeds."""
    if lang == 'mr' or not text:
        return text
    last_error = None
    for attempt in range(_retries):
        try:
            return GoogleTranslator(source='mr', target=lang).translate(text)
        except Exception as e:
            last_error = e
            time.sleep(0.3)
    return text  # fall back to Marathi only after all retries are exhausted


def translate_text_field_tracked(text, lang, failures):
    """Same as translate_text_field, but appends to `failures` (a list)
    if translation didn't actually change the text and should have —
    used so callers can decide not to cache a partially-failed result."""
    if lang == 'mr' or not text:
        return text
    result = translate_text_field(text, lang)
    if result == text:
        failures.append(text)
    return result


def translate_crop_detail_dict_per_field(details, lang):
    """Fallback path: translate each field separately (slower, ~20-30 API
    calls) — only used if the fast batched approach below fails or its
    line count doesn't match (rare)."""
    translated = {}
    failures = []
    for field_key, val in details.items():
        if field_key == 'problems':
            translated[field_key] = [
                {'issue': translate_text_field_tracked(p['issue'], lang, failures), 'solution': translate_text_field_tracked(p['solution'], lang, failures)}
                for p in val
            ]
        elif field_key == 'faq':
            translated[field_key] = [
                {'q': translate_text_field_tracked(f['q'], lang, failures), 'a': translate_text_field_tracked(f['a'], lang, failures)}
                for f in val
            ]
        elif field_key == 'pros_cons':
            translated[field_key] = {
                'pros': translate_text_field_tracked(val['pros'], lang, failures),
                'cons': translate_text_field_tracked(val['cons'], lang, failures),
            }
        elif isinstance(val, list):
            translated[field_key] = [translate_text_field_tracked(v, lang, failures) for v in val]
        elif isinstance(val, str):
            translated[field_key] = translate_text_field_tracked(val, lang, failures)
        else:
            translated[field_key] = val
    return translated, len(failures) > 0


def translate_crop_detail_dict(details, lang):
    """
    Translates every text field in a crop's CROP_DETAILS entry into the
    requested language, preserving the dict/list structure. Marathi is
    returned as-is (it's the source language of this content).

    Instead of one API call per field (20-30+ calls per page, each an
    independent chance to fail against the free translation backend),
    this joins every leaf string with newlines into ONE block, translates
    it in a single call (with retry), and splits the result back apart —
    far more reliable, since there's only one call that can fail instead
    of thirty. Falls back to the slower per-field method only if the
    batch call fails outright or the line count doesn't match afterwards
    (which would silently scramble which line belongs to which field).

    Returns (translated_dict, had_failures) so the caller can skip
    caching a partially-broken result.
    """
    if lang == 'mr':
        return details, False

    leaves = []
    for field_key, val in details.items():
        if field_key == 'problems':
            for p in val:
                leaves.append(p['issue'])
                leaves.append(p['solution'])
        elif field_key == 'faq':
            for f in val:
                leaves.append(f['q'])
                leaves.append(f['a'])
        elif field_key == 'pros_cons':
            leaves.append(val['pros'])
            leaves.append(val['cons'])
        elif isinstance(val, list):
            leaves.extend(val)
        elif isinstance(val, str):
            leaves.append(val)

    combined = "\n".join(leaves)
    translated_combined = None
    for attempt in range(2):
        try:
            translated_combined = GoogleTranslator(source='mr', target=lang).translate(combined)
            break
        except Exception:
            time.sleep(0.3)

    if translated_combined is None:
        return translate_crop_detail_dict_per_field(details, lang)

    parts = translated_combined.split("\n")
    if len(parts) != len(leaves):
        return translate_crop_detail_dict_per_field(details, lang)

    it = iter(parts)
    translated = {}
    for field_key, val in details.items():
        if field_key == 'problems':
            translated[field_key] = [{'issue': next(it), 'solution': next(it)} for _ in val]
        elif field_key == 'faq':
            translated[field_key] = [{'q': next(it), 'a': next(it)} for _ in val]
        elif field_key == 'pros_cons':
            translated[field_key] = {'pros': next(it), 'cons': next(it)}
        elif isinstance(val, list):
            translated[field_key] = [next(it) for _ in val]
        elif isinstance(val, str):
            translated[field_key] = next(it)
        else:
            translated[field_key] = val
    return translated, False


