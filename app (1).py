def _range_score(value, rng, span):
    """Generic 0-1 score: 1.0 if value is within rng, decaying outside it."""
    lo, hi = rng
    if lo <= value <= hi:
        return 1.0
    dist = min(abs(value - lo), abs(value - hi))
    return max(0.0, 1 - dist / span)


