def timing_score(crop_key):
    """
    0 to 1 score for how close the current month is to this crop's ideal
    sowing window. Perennial/year-round crops (not in CROP_SOWING_MONTHS)
    always score 1.0. Seasonal crops score 1.0 inside their window and
    decay with circular month-distance outside it.
    """
    months = CROP_SOWING_MONTHS.get(crop_key)
    if not months:
        return 1.0
    current = datetime.datetime.now().month
    if current in months:
        return 1.0
    dist = min(min(abs(current - m), 12 - abs(current - m)) for m in months)
    return max(0.0, 1 - dist / 4)


def rule_compatibility(crop_key, ph, rainfall, N, P, K, irrigation=False, waterlogging=False):
    """
    Domain-knowledge score (0 to 1) for how well the given pH, rainfall,
    and N-P-K values fit this crop's known requirements — independent of
    the ML model. Blends three sub-scores (pH, water, N-P-K) so a weak or
    unfamiliar ML signal doesn't collapse every option to near-zero.

    irrigation: True if the farmer has a supplemental water source (well/
    borewell/canal), not solely dependent on rainfall — raises the floor
    of the water score, since a shortfall from rain alone can be made up.

    waterlogging: True if water visibly pools/stays on the field after
    rain — strongly favours rice (which needs standing water) and
    penalizes every other crop (which needs good drainage).
    """
    ph_min, ph_max = CROP_PH_RANGE.get(crop_key, (5.5, 7.5))
    if ph_min <= ph <= ph_max:
        ph_score = 1.0
    else:
        dist = min(abs(ph - ph_min), abs(ph - ph_max))
        ph_score = max(0.0, 1 - dist / 3)

    water_need = crop_info.get(crop_key, {}).get('water', 'Medium')
    expected_rain = RAINFALL_EXPECTED.get(water_need, 150)
    rain_diff = abs(rainfall - expected_rain)
    water_score = max(0.0, 1 - rain_diff / 250)

    if irrigation:
        # A farmer with irrigation can make up a rainfall shortfall, so a
        # poor rainfall-only match shouldn't drag the score too low.
        water_score = max(water_score, 0.75)

    if waterlogging:
        if crop_key == 'rice':
            water_score = 1.0
        else:
            water_score = min(water_score, 0.5)

    npk_range = CROP_NPK_RANGE.get(crop_key)
    if npk_range:
        n_score = _range_score(N, npk_range['N'], 50)
        p_score = _range_score(P, npk_range['P'], 50)
        k_score = _range_score(K, npk_range['K'], 60)
        npk_score = (n_score + p_score + k_score) / 3
    else:
        npk_score = 0.5  # neutral if we have no data for this crop

    tscore = timing_score(crop_key)

    return (ph_score + water_score + npk_score + tscore) / 4


def translate_crop_name(crop_key, language):
    """
    Returns a correct, natural crop name in the target language.
    - For Marathi/Hindi: uses our own verified dictionary (never wrong).
    - For other languages: uses GoogleTranslator, but on the CLEAN display
      name ("Pigeon Pea") instead of the raw dataset key ("pigeonpeas"),
      which avoids the mistranslation bug seen with compound words.
    - Always falls back to the clean English name if anything goes wrong.
    """
    key = crop_key.lower()
    clean_name = crop_display_en.get(key, crop_key.title())

    if language in crop_translations:
        return crop_translations[language].get(key, clean_name)

    try:
        return GoogleTranslator(source='en', target=language).translate(clean_name)
    except Exception:
        return clean_name


