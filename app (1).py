def get_forecast(city):
    """
    Uses OpenWeatherMap's free 5-day/3-hour forecast endpoint and
    aggregates the 3-hour data points into one summary per day: average
    temperature, min/max, highest rain probability of the day, and a
    simple weather description — enough for a farmer to plan irrigation
    or a field visit a few days ahead. Returns [] on any failure so the
    result page can simply omit the forecast section rather than break.
    """
    try:
        url = f"https://api.openweathermap.org/data/2.5/forecast?q={city}&appid={WEATHER_API_KEY}&units=metric"
        response = requests.get(url, timeout=8)
        data = response.json()
        if str(data.get('cod')) != '200':
            return []

        days = {}
        for entry in data['list']:
            date_str = entry['dt_txt'].split(' ')[0]
            days.setdefault(date_str, []).append(entry)

        forecast = []
        for date_str, entries in list(days.items())[:5]:
            temps = [e['main']['temp'] for e in entries]
            pops = [e.get('pop', 0) for e in entries]
            # pick the entry closest to midday for a representative description/icon
            midday = min(entries, key=lambda e: abs(int(e['dt_txt'].split(' ')[1].split(':')[0]) - 13))
            desc = midday['weather'][0]['main']
            emoji, desc_mr = WEATHER_DESC_MAP.get(desc, ('🌡️', desc))
            y, m, d = map(int, date_str.split('-'))
            weekday_idx = datetime.date(y, m, d).weekday()
            forecast.append({
                'weekday_idx': weekday_idx,
                'date': f"{d}/{m}",
                'min_temp': round(min(temps)),
                'max_temp': round(max(temps)),
                'rain_chance': round(max(pops) * 100),
                'desc': desc_mr,
                'emoji': emoji,
            })
        return forecast
    except Exception:
        return []


def predict_top3(sample):
    """Plain model prediction, no regional awareness at all."""
    proba = model.predict_proba([sample])[0]
    classes = model.classes_
    top3_idx = np.argsort(proba)[-3:][::-1]
    results = []
    for i in top3_idx:
        results.append((classes[i], round(proba[i] * 100, 2)))
    return results


def predict_top3_regional(sample, city):
    """
    Regional-aware prediction (hybrid ML + domain-rule approach):
    - Get the model's probability for EVERY crop (not just the raw top-3).
    - If the city is a recognized Maharashtra district, rank ONLY the
      crops that are realistically grown there, and return the best
      matches among those.
    - If the city is not recognized, or none of its allowed crops got
      any meaningful probability, fall back to the plain top-3.
    """
    proba = model.predict_proba([sample])[0]
    classes = model.classes_
    city_key = city.lower().strip()

    if city_key in maharashtra_region_crops:
        allowed = set(maharashtra_region_crops[city_key])
        allowed_indices = [i for i, c in enumerate(classes) if c.lower() in allowed]

        if allowed_indices:
            allowed_indices.sort(key=lambda i: proba[i], reverse=True)
            top_indices = allowed_indices[:3]
            return [(classes[i], round(proba[i] * 100, 2)) for i in top_indices]

    top3_idx = np.argsort(proba)[-3:][::-1]
    return [(classes[i], round(proba[i] * 100, 2)) for i in top3_idx]


def predict_top3_split(sample, city, ph, rainfall, irrigation=False, waterlogging=False):
    """
    Splits predictions into two groups:
    - 'traditional': crops that match this district's typical crop list.
      Ranked using a HYBRID score — 40% ML probability + 60% agronomic
      rule compatibility (pH + water need vs rainfall) — so the ranking
      stays meaningful even when the raw ML confidence is very low for
      every option in the district's allowed list.
    - 'other': crops outside that typical list but with meaningful raw
      ML confidence — shown separately as "other possibilities /
      experimental crops". These stay ranked by pure ML probability,
      since they're explicitly the "what does the model alone think"
      view for farmers experimenting outside the traditional list.
    If the city isn't a recognized district, everything goes into
    'traditional' (plain top-3 by ML) and 'other' is empty.
    """
    proba = model.predict_proba([sample])[0]
    classes = model.classes_
    city_key = city.lower().strip()
    N_val, P_val, K_val = sample[0], sample[1], sample[2]

    if city_key in maharashtra_region_crops:
        allowed = set(maharashtra_region_crops[city_key])
        allowed_idx = [i for i, c in enumerate(classes) if c.lower() in allowed]
        other_idx = [i for i, c in enumerate(classes) if c.lower() not in allowed]

        if allowed_idx:
            max_p = max(proba[i] for i in allowed_idx) or 1.0
            hybrid_scores = {}
            for i in allowed_idx:
                crop_key = classes[i].lower()
                ml_norm = proba[i] / max_p
                rule = rule_compatibility(crop_key, ph, rainfall, N_val, P_val, K_val, irrigation, waterlogging)
                hybrid_scores[i] = 0.4 * ml_norm + 0.6 * rule
            allowed_idx.sort(key=lambda i: hybrid_scores[i], reverse=True)
            traditional = [(classes[i], round(hybrid_scores[i] * 100, 2)) for i in allowed_idx[:3]]
        else:
            traditional = []

        other_idx.sort(key=lambda i: proba[i], reverse=True)
        other = [(classes[i], round(proba[i] * 100, 2)) for i in other_idx[:3]]

        if not traditional:
            # nothing matched the district list at all — fall back
            top3_idx = np.argsort(proba)[-3:][::-1]
            traditional = [(classes[i], round(proba[i] * 100, 2)) for i in top3_idx]
            other = []

        return traditional, other

    top3_idx = np.argsort(proba)[-3:][::-1]
    traditional = [(classes[i], round(proba[i] * 100, 2)) for i in top3_idx]
    return traditional, []


