def fertilizer_recommendation(N, P, K, crop_key=None):
    """
    Compares the farmer's soil N-P-K against the TARGET crop's own ideal
    range (via CROP_NPK_RANGE) when known, instead of one generic ideal
    (80/40/40) for every crop — a rice field genuinely needs more nitrogen
    than a chickpea field, for example.
    """
    npk_range = CROP_NPK_RANGE.get(crop_key) if crop_key else None
    if npk_range:
        ideal_N = sum(npk_range['N']) / 2
        ideal_P = sum(npk_range['P']) / 2
        ideal_K = sum(npk_range['K']) / 2
